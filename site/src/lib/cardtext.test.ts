import assert from "node:assert/strict";
import { test } from "node:test";

import { restAfterTitle } from "./cardtext.ts";

test("заголовок - вся первая строка: в карточке следующие строки", () => {
    assert.equal(
        restAfterTitle(
            "День открытых дверей\n\nЖдем всех в субботу.",
            "День открытых дверей",
        ),
        "Ждем всех в субботу.",
    );
});

test("обрезанный заголовок: остаток строки с многоточием, без повтора", () => {
    assert.equal(
        restAfterTitle(
            "Осень - пора прогулок, игр с листьями и дарами осени.\nВторая строка.",
            "Осень - пора прогулок…",
        ),
        "…игр с листьями и дарами осени.\nВторая строка.",
    );
});

test("пустые строки в начале поста не мешают", () => {
    assert.equal(restAfterTitle("\n  Заголовок\nТекст", "Заголовок"), "Текст");
});

test("пост из одной строки: текста под заголовком нет", () => {
    assert.equal(restAfterTitle("Только заголовок", "Только заголовок"), "");
});

test("заголовок не из текста (по дате) - текст целиком", () => {
    assert.equal(
        restAfterTitle("Текст поста", "Новость от 12 октября 2026"),
        "Текст поста",
    );
    assert.equal(restAfterTitle("Текст поста", ""), "Текст поста");
});

test("ссылка в строке заголовка: воркер ее вырезал, в карточке повтора нет", () => {
    assert.equal(
        restAfterTitle(
            'Специалисты ЦКП : ,,Добромир"https://vk.ru/album-1_2',
            'Специалисты ЦКП : ,,Добромир"',
        ),
        "",
    );
    assert.equal(
        restAfterTitle(
            "https://vk.ru/album-1_2\nВторая строка\nТретья",
            "Вторая строка",
        ),
        "Третья",
    );
});
